import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createReplayEngine,formatLap,formatGap,lastAt} from '../dist/engine.js';
const data=JSON.parse(fs.readFileSync(new URL('../dist/replay.json',import.meta.url),'utf8'));
const engine=createReplayEngine(data);
const before=engine.snapshot(engine.startTime-1);
assert.equal(before.started,false);
assert.ok(before.rows.every(r=>r.lastLap===null));
const snapshot=engine.snapshot(data.session.defaultTime);
assert.equal(snapshot.lap,36);
assert.equal(snapshot.rows.length,20);
assert.equal(snapshot.rows[0].code,'VER');
assert.equal(snapshot.rows.find(r=>r.number===14).status,'retired');
assert.equal(snapshot.rows.find(r=>r.number===27).status,'dns');
assert.ok(snapshot.rows.every(r=>r.laps.every(l=>l.end<=snapshot.t+0.001)));
assert.equal(engine.snapshot(2200).rows.find(r=>r.number===14).status,'running');
assert.equal(engine.snapshot(engine.endTime).fastestLap.time,80.901);
assert.equal(engine.snapshot(engine.endTime).fastestLap.code,'NOR');
assert.equal(engine.snapshot(engine.endTime).rows.find(r=>r.number===4).completedLaps,53);
assert.equal(engine.snapshot(engine.endTime).flag,'CHEQUERED');
assert.equal(engine.snapshot(engine.endTime).rows.filter(r=>r.status==='finished').length,18);
assert.equal(formatLap(80.901),'1:20.901');
assert.equal(formatGap('+1 LAP'),'+1 okr.');
assert.equal(formatGap(null),'—');
assert.equal(lastAt([{t:1,v:1},{t:3,v:2}],2).v,1);
console.log(JSON.stringify({assertions:'passed',start:engine.startTime,end:engine.endTime,default:{lap:snapshot.lap,leader:snapshot.rows[0].code,flag:snapshot.flag,fastestLap:snapshot.fastestLap,weather:snapshot.weather},finalFastestLap:engine.snapshot(engine.endTime).fastestLap},null,2));
const final=engine.snapshot(engine.endTime);
assert.deepEqual(final.rows.filter(r=>r.position!=null).map(r=>r.position),Array.from({length:18},(_,i)=>i+1));
for(const result of data.results){const row=final.rows.find(r=>r.number===result.driver);assert.equal(row.position,result.position);assert.equal(row.gap,result.gap);}
assert.equal(final.rows.at(-2).status,'retired');
assert.equal(final.rows.at(-1).status,'dns');
assert.equal(final.rows.find(r=>r.number===18).gap,'+1 LAP');
const activeEngine=createReplayEngine({...data,session:{...data.session,isActive:true,totalLapsKnown:false}});
const active=activeEngine.snapshot(engine.endTime);
assert.equal(active.finished,false);
assert.equal(active.totalLapsKnown,false);
assert.ok(active.rows.filter(r=>r.status==='running').length>0);
console.log('Final classification and active-session edge cases: passed');
